import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const jsonPath = resolve(repoRoot, "datasets-config/iso3166-alpha2.json");
const countries = readCountrySource(jsonPath);

function readCountrySource(path) {
  const raw = JSON.parse(readFileSync(path, "utf8"));
  if (!Array.isArray(raw.countries) || raw.countries.length === 0) {
    throw new Error(`expected { countries: [...] } in ${path}`);
  }
  const seen = new Set();
  for (const entry of raw.countries) {
    const { code, name } = entry ?? {};
    if (typeof code !== "string" || !/^[A-Z]{2}$/.test(code)) {
      throw new Error(`invalid country code in ${path}: ${JSON.stringify(code)}`);
    }
    if (seen.has(code)) {
      throw new Error(`duplicate country code in ${path}: ${code}`);
    }
    seen.add(code);
    if (typeof name !== "string" || name.trim() === "") {
      throw new Error(`missing name for country code ${code} in ${path}`);
    }
  }
  return [...raw.countries].sort((a, b) => a.code.localeCompare(b.code));
}

function writeGo() {
  const entries = countries.map((c) => `\t"${c.code}": {}`).join(",\n");
  const body = `package contracts

// Code generated by datasets-config/gen-country-codes.mjs. DO NOT EDIT.
// Source of truth: datasets-config/iso3166-alpha2.json

import "regexp"

// validCountryCode matches an uppercase ISO 3166-1 alpha-2 code.
var validCountryCode = regexp.MustCompile(\`^[A-Z]{2}$\`)

// allowedCountryCodes is the set of officially assigned ISO 3166-1 alpha-2
// codes. Exceptional reservations (EU, UN) and user-reserved ranges are
// intentionally excluded.
var allowedCountryCodes = map[string]struct{}{
${entries},
}

// IsCountryCodeAllowed reports whether code is an officially assigned ISO 3166-1
// alpha-2 code. It requires the exact uppercase form.
func IsCountryCodeAllowed(code string) bool {
\tif !validCountryCode.MatchString(code) {
\t\treturn false
\t}
\t_, ok := allowedCountryCodes[code]
\treturn ok
}
`;
  const out = resolve(repoRoot, "pkg/contracts/iso3166.go");
  writeFileSync(out, body, "utf8");
  console.log(`wrote ${out}`);
}

function writeTSAllowlist() {
  const list = countries.map((c) => `\t"${c.code}",`).join("\n");
  const body = `// Code generated by datasets-config/gen-country-codes.mjs. DO NOT EDIT.
// Source of truth: datasets-config/iso3166-alpha2.json

export const COUNTRY_CODE_ALLOWLIST: ReadonlySet<string> = new Set<string>([
${list}
]);

const COUNTRY_CODE_REGEX = /^[A-Z]{2}$/;

export function isAllowedCountryCode(code: string): boolean {
  if (!COUNTRY_CODE_REGEX.test(code)) {
    return false;
  }
  return COUNTRY_CODE_ALLOWLIST.has(code);
}

// countryCodeToEmoji maps an ISO 3166-1 alpha-2 code to its Regional Indicator
// flag emoji. It only ever emits the two-letter regional indicator sequence,
// never arbitrary Unicode, so injection of ZWJ / skin-tone / combining sequences
// is impossible. Returns "" for an invalid or disallowed code.
export function countryCodeToEmoji(code: string): string {
  if (!isAllowedCountryCode(code)) {
    return "";
  }
  const upper = code.toUpperCase();
  const first = 0x1f1e6 + (upper.charCodeAt(0) - 65);
  const second = 0x1f1e6 + (upper.charCodeAt(1) - 65);
  return String.fromCodePoint(first, second);
}
`;
  const out = resolve(repoRoot, "apps/web/lib/country-flag.ts");
  writeFileSync(out, body, "utf8");
  console.log(`wrote ${out}`);
}

function writeTSNames() {
  const entries = countries.map((c) => `\t${c.code}: ${JSON.stringify(c.name)},`).join("\n");
  const body = `// Code generated by datasets-config/gen-country-codes.mjs. DO NOT EDIT.
// Source of truth: datasets-config/iso3166-alpha2.json

export const COUNTRY_NAMES: Readonly<Record<string, string>> = {
${entries}
};
`;
  const out = resolve(repoRoot, "apps/web/lib/country-names.ts");
  writeFileSync(out, body, "utf8");
  console.log(`wrote ${out}`);
}

writeGo();
writeTSAllowlist();
writeTSNames();
console.log(`regenerated from ${countries.length} countries in ${jsonPath}`);
